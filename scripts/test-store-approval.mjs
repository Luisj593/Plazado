current={...before.stores[0],id:'other'};
await assert.rejects(repository.persistCheckout(before,after,false),/cambió en otra sesión/);
console.log('Store approval: legacy document-path IDs accepted; concurrent edits and conflicting embedded IDs rejected. No production data used.');
