const start=source.indexOf('  public async persistCheckout(');
const end=source.indexOf('\n  public ',start+5);
const method=source.slice(start,end);
const code=await transform(`class Harness {adminDb:any; constructor(db:any){this.adminDb=db;} ${method}}`,{loader:'ts'});
const Harness=new Function('commerceChanges','firestoreSafe','isStorePubliclyVisible','isProductPubliclyVisible',code.code+';return Harness;')(mod.exports.commerceChanges,x=>x,()=>true,()=>true);
